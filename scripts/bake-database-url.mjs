import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "src/lib/generated-database-url.ts");

function loadEnvFile(filePath) {
  if (!existsSync(filePath)) return;
  for (const line of readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}

loadEnvFile(join(root, ".env.local"));
loadEnvFile(join(root, ".env"));

const url = (process.env.DATABASE_URL || "").trim();

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `/** Auto-generated by scripts/bake-database-url.mjs — do not edit. */
export const GENERATED_DATABASE_URL: string | null = ${
    url ? JSON.stringify(url) : "null"
  };
`,
);

console.log(
  url
    ? "Baked DATABASE_URL into src/lib/generated-database-url.ts"
    : "No DATABASE_URL set — baked null (RSVP will need runtime env)",
);
